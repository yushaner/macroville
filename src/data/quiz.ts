export type QuizType = 'single' | 'multi' | 'judge';

export interface QuizDef {
  key: string; // 对应 glossary 里的名词 key
  type: QuizType;
  stem: string; // 题干
  options: string[];
  answer: number[]; // 正确选项下标（多选可多个）
  explain: string; // 解析
  source: string; // 考点出处
}

const S = (
  key: string, stem: string, options: string[], a: number, explain: string, source: string,
): QuizDef => ({ key, type: 'single', stem, options, answer: [a], explain, source });

const D = (
  key: string, stem: string, options: string[], a: number[], explain: string, source: string,
): QuizDef => ({ key, type: 'multi', stem, options, answer: a, explain, source });

const J = (
  key: string, stem: string, ok: boolean, explain: string, source: string,
): QuizDef => ({ key, type: 'judge', stem, options: ['正确', '错误'], answer: [ok ? 0 : 1], explain, source });

